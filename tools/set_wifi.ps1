# Dien SSID / mat khau Wi-Fi vao firmware_esp32\main\wifi_secret.h
#
# Vi du:
#   powershell -ExecutionPolicy Bypass -File tools\set_wifi.ps1 -Ssid "NhaToi" -Password "matkhau123"
#   powershell -ExecutionPolicy Bypass -File tools\set_wifi.ps1 -Ssid "NhaToi" -Password "matkhau123" -Build -Flash -Port COM3
#
# File wifi_secret.h KHONG duoc commit (co trong .gitignore).

param(
    [Parameter(Mandatory = $true)][string]$Ssid,
    [string]$Password = "",
    [switch]$Build,
    [switch]$Flash,
    [string]$Port = "COM3"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$hdr  = Join-Path $root "firmware_esp32\main\wifi_secret.h"

if ($Ssid -match '["\\]') { throw "SSID khong duoc chua dau ngoac kep hoac dau \\" }
if ($Password -match '["\\]') { throw "Mat khau khong duoc chua dau ngoac kep hoac dau \\" }

$content = @"
// [generated by tools/set_wifi.ps1] — file nay bi gitignore, khong commit
#ifndef WIFI_SECRET_H_
#define WIFI_SECRET_H_

#define TD_WIFI_SSID     "$Ssid"
#define TD_WIFI_PASSWORD "$Password"

#endif // WIFI_SECRET_H_
"@
Set-Content -Path $hdr -Value $content -Encoding ASCII
Write-Host "da ghi $hdr" -ForegroundColor Green
Write-Host "  SSID     : $Ssid"
Write-Host ("  Password : " + $(if ($Password) { "*** (" + $Password.Length + " ky tu)" } else { "(mang mo)" }))

if ($Build) {
    $py = "C:\Espressif\python_env\idf5.3_py3.11_env\Scripts\python.exe"
    if (-not (Test-Path $py)) { throw "khong thay python cua ESP-IDF: $py" }
    $idf = "C:\Espressif\frameworks\esp-idf-v5.3.5"
    Write-Host "== build lai firmware ==" -ForegroundColor Cyan
    & $py "$idf\tools\idf.py" -C (Join-Path $root "firmware_esp32") `
        -D SDKCONFIG="$(Join-Path $root 'firmware_esp32\sdkconfig')" build
    if ($LASTEXITCODE -ne 0) { throw "build loi" }
    $app = Join-Path $root "firmware_esp32\build\tinydriver_esp32s3_edge_ai.bin"
    Write-Host ("app moi: " + (Get-FileHash $app -Algorithm SHA256).Hash) -ForegroundColor Green
    if ($Flash) {
        Write-Host "== nap app ==" -ForegroundColor Cyan
        & $py -m esptool --chip esp32s3 -p $Port -b 921600 write_flash 0x10000 $app
    }
} elseif ($Flash) {
    Write-Host "can -Build thi moi co app moi de nap" -ForegroundColor Yellow
}

Write-Host "xong. Mo web theo IP in ra trong log serial (115200)." -ForegroundColor Green
